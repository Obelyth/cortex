describe("loadCorpus — cache under stress", () => {
  const origFetch = globalThis.fetch;

  const gzTar = (map: Record<string, string>) =>
    zlib.gzipSync(
      tar(...Object.entries(map).map(([n, b]) => entry({ name: `brain-abc123/${n}` }, b)), END)
    );

  beforeEach(() => {
    __setCache(null);
    process.env.BRAIN_REPO = "acme/brain";
    process.env.GITHUB_TOKEN = "t";
  });
  afterEach(() => {
    globalThis.fetch = origFetch;
    __setCache(null);
  });

  // REACHABLE. Two MCP requests landing on the same cold Vercel instance is the normal case,
  // not an edge case. Both miss, both fetch, both gunzip and both build a full corpus.
  it("OK: two concurrent cold calls share one fetch and one build", async () => {
    const tarball = gzTar({ "profile.md": "operator" });
    let tarballCalls = 0;
    globalThis.fetch = (async (url: string) => {
      if (String(url).includes("/commits/")) {
        return new Response(JSON.stringify({ sha: "sha1" }), { status: 200 });
      }
      tarballCalls++;
      await new Promise((r) => setTimeout(r, 20)); // the race window
      return new Response(new Uint8Array(tarball), { status: 200 });
    }) as typeof fetch;

    const [a, b] = await Promise.all([loadCorpus(), loadCorpus()]);
    expect(tarballCalls).toBe(1); // an in-flight promise should be shared
    expect(a).toBe(b); // and both callers should see the same object
  });

  it("OK: a failed tarball fetch never clobbers a good cache and never exposes half a corpus", async () => {
    const tarball = gzTar({ "profile.md": "operator", "projects/beacon.md": "dark" });
    let head = "sha1";
    let tarballCalls = 0;
    globalThis.fetch = (async (url: string) => {
      if (String(url).includes("/commits/")) {
        return new Response(JSON.stringify({ sha: head }), { status: 200 });
      }
      tarballCalls++;
      return head === "sha1"
        ? new Response(new Uint8Array(tarball), { status: 200 })
        : new Response("nope", { status: 404 });
    }) as typeof fetch;

    const warm = await loadCorpus();
    expect(warm.files.size).toBe(2);

    head = "sha2"; // a new commit whose tarball is unavailable
    await expect(loadCorpus()).rejects.toThrow(/HTTP 404/);

    head = "sha1"; // the old corpus is still intact and still served without a refetch
    const before = tarballCalls;
    expect(await loadCorpus()).toBe(warm);
    expect(tarballCalls).toBe(before);
  });

  // REACHABLE. GitHub 5xx and secondary rate limits are ordinary events. Today the head call
  // is a hard dependency on EVERY request: a complete, verified corpus sits in memory and the
  // brain still answers with an exception. Serving the cached corpus is not "half a brain" —
  // it is a whole one, and every answer already carries the commit it was proven against, so
  // staleness stays visible. This is a policy call, not a correctness defect; recorded here
  // because the current policy is unstated and maximally brittle.
  it("BUG(policy): a transient head-sha failure takes the brain down despite a warm cache", async () => {
    const tarball = gzTar({ "profile.md": "operator" });
    let headOk = true;
    globalThis.fetch = (async (url: string) => {
      if (String(url).includes("/commits/")) {
        return headOk
          ? new Response(JSON.stringify({ sha: "sha1" }), { status: 200 })
          : new Response("upstream", { status: 502 });
      }
      return new Response(new Uint8Array(tarball), { status: 200 });
    }) as typeof fetch;

    const warm = await loadCorpus();
    headOk = false;
    await expect(loadCorpus()).resolves.toBe(warm);
  });
});

