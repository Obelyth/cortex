describe("isLive — bypasses", () => {
  it("OK: exclusion is a literal prefix match — these shapes bypass it, none are reachable", () => {
    // Documented, not fixed: git cannot emit "./" or ".." path components, and the corpus
    // paths come from nowhere else. The list matters if untar ever normalises paths, or if a
    // second producer (a local clone walker) is ever added.
    expect(isLive("tools//foo.md")).toBe(false); // still caught — the prefix is intact
    expect(isLive("./tools/foo.md")).toBe(true); // BYPASS
    expect(isLive("notes/../tools/secret.md")).toBe(true); // BYPASS
    expect(isLive("TOOLS/foo.md")).toBe(true); // BYPASS — comparison is case-sensitive
    expect(isLive("Archive/old.md")).toBe(true); // BYPASS
  });

  it("OK: the .md test is case-INsensitive, so a note named X.MD is in the corpus", () => {
    // Was the only bypass on this list the operator could trigger by hand, and it failed toward
    // omission: the note exists and the brain answered NOT IN BRAIN for it. brain_ask.py's
    // live_files() carries the same case-insensitive test, or the two corpora drift.
    expect(isLive("notes/Setup.MD")).toBe(true);
    expect(isLive("notes/Setup.Md")).toBe(true);
    expect(isLive("notes/setup.markdown")).toBe(false);
  });

  it("OK: exclusions key off the directory, not a substring", () => {
    expect(isLive("archive.md")).toBe(true); // a note named archive, not the archive dir
    expect(isLive("archive")).toBe(false); // not markdown
    expect(isLive("notes/toolsy/x.md")).toBe(true);
    expect(isLive("brain-index.md")).toBe(false);
    expect(isLive("deep/nested/brain-index.md")).toBe(false); // SKIP_NAME is a basename test
  });
});

