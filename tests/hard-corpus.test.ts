describe("untar — malformed input", () => {
  // THEORETICAL over HTTPS to GitHub: a truncated download fails in gunzip long before untar
  // sees it. Recorded because the failure mode is the worst kind for this system — a note is
  // served SHORT, with no error, and the reader answers confidently from half a note.
  it("OK: a size larger than the remaining buffer is refused, not silently truncated", () => {
    const header = makeHeader({ name: "brain-abc123/notes/a.md", size: 4096 });
    const buf = tar([header, Buffer.from("only 512 bytes of this file survived".padEnd(BLOCK, " "))]);
    // Refuses the whole archive: emitting a short note as though complete is the one thing
    // this reader must never do.
    expect(() => untar(buf)).toThrow(/declares 4096 bytes/);
  });

  // THEORETICAL. `parseInt(field, 8)` accepts a leading "-": a size of -512 makes
  // `off += Math.ceil(size / 512) * 512` walk BACKWARDS onto the same header, forever. A big
  // negative walks off past zero, where buf.toString clamps a negative start to 0 and returns
  // "", so `off` crawls back up 512 bytes at a time and re-reads the same poisoned header.
  // untar is synchronous, so this pins the function's event loop until the platform timeout.
  it("OK: a negative size field is rejected instead of looping forever", () => {
    const good = tar(entry({ name: "brain-abc123/notes/a.md" }, "alpha"), END);
    expect(() => untar(budgeted(good, 50_000))).not.toThrow(); // control: budget is generous

    const evil = tar(
      [makeHeader({ name: "brain-abc123/notes/a.md", sizeField: "-0000001000" })],
      Buffer.alloc(BLOCK),
      END
    );
    // Rejected outright, so `off` never walks backwards and the loop always terminates.
    expect(() => untar(budgeted(evil, 50_000))).toThrow(/not octal|declares size/);
  });

  // THEORETICAL. The `if (!name)` branch skips the size field, so a nameless header's PAYLOAD
  // is reinterpreted as tar headers. That is an entry-injection primitive: file bytes become
  // corpus entries. It needs a malformed archive to trigger, but the consequence is the one
  // thing this system must never do — serve text that is not what the repo holds.
  it("OK: a nameless header is refused, so its payload cannot be parsed as headers", () => {
    const phantom = tar(entry({ name: "brain-abc123/notes/injected.md" }, "not in the repo"));
    const buf = tar([makeHeader({ name: "", size: phantom.length })], phantom, END);
    expect(() => untar(buf)).toThrow(/no path below the archive root/);
  });

  // THEORETICAL. Nothing stops at the two zero blocks; the reader scans to the end of the
  // buffer, so anything appended to a valid archive is ingested as corpus.
  it("OK: entries after the end-of-archive marker are not ingested", () => {
    const buf = tar(
      entry({ name: "brain-abc123/notes/real.md" }, "real"),
      END,
      entry({ name: "brain-abc123/notes/appended.md" }, "appended after EOF"),
      END
    );
    const got = files(buf);
    expect(got.get("notes/real.md")).toBe("real");
    expect(got.has("notes/appended.md")).toBe(false);
  });

  it("OK: a header truncated mid-block is ignored rather than throwing", () => {
    const buf = tar(entry({ name: "brain-abc123/notes/a.md" }, "alpha"), [Buffer.alloc(200)]);
    expect(untar(buf)).toEqual([["notes/a.md", "alpha"]]);
  });

  it("OK: a non-octal size field is refused rather than coerced to 0", () => {
    // The old reader did `parseInt(field, 8) || 0`, so "99999999999" became size 0 and the
    // entry was emitted EMPTY — a note served as blank rather than as missing or as an error.
    const buf = tar([makeHeader({ name: "brain-abc123/notes/a.md", sizeField: "99999999999" })], END);
    expect(() => untar(buf)).toThrow(/not octal/);
  });
});

