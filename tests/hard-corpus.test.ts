describe("gh() — Authorization on the tarball redirect", () => {
  /** Two servers on different ports = different origins. */
  async function listen(handler: http.RequestListener): Promise<{ url: string; close: () => Promise<void> }> {
    const s = http.createServer(handler);
    await new Promise<void>((r) => s.listen(0, "127.0.0.1", r));
    const port = (s.address() as AddressInfo).port;
    return {
      url: `http://127.0.0.1:${port}`,
      close: () => new Promise<void>((r) => s.close(() => r())),
    };
  }

  it("OK: fetch strips Authorization on a cross-origin redirect, and keeps it same-origin", async () => {
    // corpus.ts's header comment stakes the whole two-request design on this: the API 302s to
    // codeload with a pre-signed URL, and the token must not ride along to the second host.
    // gh() passes no `redirect` option, so this platform behaviour IS the protection.
    let seen: string | undefined | null = "unset";
    const dest = await listen((req, res) => {
      seen = req.headers.authorization ?? null;
      res.end("ok");
    });
    const hop = await listen((req, res) => {
      if (req.url === "/same") {
        seen = req.headers.authorization ?? null;
        res.end("ok");
        return;
      }
      res.writeHead(302, { Location: req.url === "/cross" ? `${dest.url}/x` : "/same" });
      res.end();
    });
    try {
      await fetch(`${hop.url}/cross`, { headers: { Authorization: "Bearer SECRET" } });
      expect(seen).toBe(null); // codeload never sees the token

      await fetch(`${hop.url}/inner`, { headers: { Authorization: "Bearer SECRET" } });
      expect(seen).toBe("Bearer SECRET"); // and a same-origin hop still authenticates
    } finally {
      await hop.close();
      await dest.close();
    }
  });
});
