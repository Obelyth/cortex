describe("untar — encoding", () => {
  it("OK: multi-byte UTF-8 bodies and filenames round-trip exactly", () => {
    // The size field is a BYTE count and the slice is exact, so there is no boundary to split.
    const body = "café — naïve — 🧠 ünïcödé\nsecond line\n";
    const buf = tar(entry({ name: "brain-abc123/notes/café-🧠.md" }, body), END);
    expect(files(buf).get("notes/café-🧠.md")).toBe(body);
  });

  it("OK: a name that fills the whole 100-byte field with no NUL terminator is read intact", () => {
    const name = "brain-abc123/notes/" + "n".repeat(100 - 19 - 3) + ".md";
    expect(Buffer.byteLength(name)).toBe(100);
    const buf = tar(entry({ name }, "body"), END);
    expect(files(buf).get(name.slice("brain-abc123/".length))).toBe("body");
  });

  it("OK: a NUL byte inside a file body survives (only the name fields are NUL-trimmed)", () => {
    const body = "before\0after";
    const buf = tar(entry({ name: "brain-abc123/notes/nul.md" }, body), END);
    expect(files(buf).get("notes/nul.md")).toBe(body);
  });

  it("OK: untar materialises every entry as a string before isLive can filter it", () => {
    // Not a bug, a cost: a binary blob anywhere in the repo (tools/, .github/, an image) is
    // fully UTF-8 decoded into a JS string and only then discarded by loadCorpus's filter.
    // There is no cap anywhere on the decoded total.
    const blob = Buffer.alloc(64 * 1024, 0xff);
    const buf = tar(entry({ name: "brain-abc123/tools/blob.bin" }, blob), END);
    expect(files(buf).get("tools/blob.bin")!.length).toBeGreaterThan(0);
  });
});

