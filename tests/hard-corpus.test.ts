describe("untar — path traversal", () => {
  it("OK: a traversing entry name is inert — the path is only ever a Map key", () => {
    // git refuses to store ".." or a leading "/" in a tree, so this cannot come out of the
    // GitHub tarball at all. And nothing in lib/ touches the filesystem — the corpus path is
    // a Map key, a line in the prompt, and a lookup in checkCitation. Nothing resolves it.
    // Worth pinning anyway so a future "write the corpus to disk" change is forced to notice.
    const buf = tar(
      entry({ name: "brain-abc123/../../../etc/passwd.md" }, "root:x:0:0"),
      entry({ name: "/etc/shadow.md" }, "shadow"),
      END
    );
    const got = files(buf);
    expect(got.get("../../../etc/passwd.md")).toBe("root:x:0:0"); // survives as a key, nothing more
    expect(got.get("etc/shadow.md")).toBe("shadow"); // absolute path: slice(1) eats the empty head
    expect(isLive("../../../etc/passwd.md")).toBe(true); // and it does reach the corpus
    expect(isLive("../../../etc/passwd")).toBe(false); // ...only if it ends in .md
  });
});

