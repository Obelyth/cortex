describe("untar — tar formats git actually emits", () => {
  // LATENT, not firing today — but it is one long filename away, and it fails silently.
  //
  // Verified against real `git archive --prefix=`, which is exactly what
  // GET /repos/{o}/{r}/tarball/{ref} runs. When a path will not fit in name(100) +
  // prefix(155) split at a "/", git does NOT truncate — it writes a pax extended header
  // ('x') carrying `path=<real path>` and names the data entry "<oid>.data".
  //
  // That name has no "/" in it, so `full.split("/").slice(1).join("/")` produces "" and the
  // `if (rel)` guard throws the file away. Same failure as the prefix bug: a live note
  // vanishes from the corpus and the brain answers NOT IN BRAIN for a fact it holds.
  //
  // Measured budget. GitHub's wrapper is "<owner>-<repo>-<7-char-sha>/" — verified against a
  // real tarball, it is the SHORT sha even when you request a full one — so ~26 bytes for
  // this repo. git then splits at the last "/" at index <=155, and everything after it must
  // fit in 100 BYTES. So the trigger is: a note whose BASENAME exceeds 100 bytes (non-ASCII
  // counts 2-4 bytes per character). The longest basename in the brain today is 47 bytes, so
  // this is not firing — it fires the day a generated note title runs long.
  it("OK: a pax extended header ('x') names the entry that follows it", () => {
    const wrapper = "brain-abc123/";
    const long = "a".repeat(110) + ".md";
    const full = `${wrapper}memory-2026-07/${long}`;
    const oid = "29e8e3cd1b193db4d9e5e589fd1a800df2fca220";
    const record = paxRecord("path", full);

    const buf = tar(
      // git writes this first, verbatim, on every tarball.
      entry({ name: "pax_global_header", type: "g" }, paxRecord("comment", oid)),
      entry({ name: wrapper, type: "5" }),
      entry({ name: `${wrapper}memory-2026-07/`, type: "5" }),
      entry({ name: `${oid}.paxheader`, type: "x" }, record),
      entry({ name: `${oid}.data`, type: "0" }, "long basename note\n"),
      entry({ name: `${wrapper}memory-2026-07/short.md`, type: "0" }, "short\n"),
      END
    );

    const got = files(buf);
    expect(got.get("memory-2026-07/short.md")).toBe("short\n"); // control: parser stayed aligned
    expect(got.get(`memory-2026-07/${long}`)).toBe("long basename note\n");
  });

  it("OK: a 'g' global header never renames the entries that follow it", () => {
    // git writes exactly one `pax_global_header` per archive, carrying a comment. Only a
    // per-file 'x' header may rename the next entry — treating 'g' the same way would apply
    // one path record to every remaining entry in the archive.
    const buf = tar(
      entry({ name: "pax_global_header", type: "g" }, paxRecord("comment", "deadbeef")),
      entry({ name: "brain-abc123/notes/a.md", type: "0" }, "alpha"),
      entry({ name: "brain-abc123/notes/b.md", type: "0" }, "bravo"),
      END
    );
    expect(files(buf).get("notes/a.md")).toBe("alpha");
    expect(files(buf).get("notes/b.md")).toBe("bravo");
  });

  it("OK: an 'x' header renames only the single entry that follows it", () => {
    const buf = tar(
      entry({ name: `${"b".repeat(40)}.paxheader`, type: "x" },
        paxRecord("path", "brain-abc123/notes/renamed.md")),
      entry({ name: "brain-abc123/deadbeef.data", type: "0" }, "bravo"),
      entry({ name: "brain-abc123/notes/after.md", type: "0" }, "after"),
      END
    );
    const got = files(buf);
    expect(got.get("notes/renamed.md")).toBe("bravo");
    expect(got.get("notes/after.md")).toBe("after");
    expect(got.has("deadbeef.data")).toBe(false);
  });

  // THEORETICAL for GitHub (git never writes 'L'; it uses pax). Reachable only if a tarball
  // is ever produced by GNU tar instead — e.g. a mirror, a local fixture, or a future change
  // that unpacks an archive from anywhere else.
  it("OK: a GNU longname ('L') entry is stored under its full name", () => {
    const wrapper = "brain-abc123/";
    const full = `${wrapper}notes/${"n".repeat(110)}.md`;
    const buf = tar(
      entry({ name: "././@LongLink", type: "L" }, full + "\0"),
      entry({ name: full.slice(0, 100), type: "0" }, "body"),
      END
    );
    const got = files(buf);
    expect(got.get(full.slice(wrapper.length))).toBe("body");
  });

  // THEORETICAL. base-256 kicks in past 8 GB and git uses a pax `size` record there anyway.
  // Recorded because the failure is silent and total: buf.toString("ascii") MASKS THE HIGH BIT
  // (0x80 -> 0x00), so the field reads as NUL, size becomes 0, and the payload is then parsed
  // as tar headers — everything after it in the archive is garbage.
  it("OK: a base-256 (binary) size field is decoded, not read as 0", () => {
    const body = Buffer.alloc(BLOCK, 0x41);
    const sizeField = Buffer.alloc(12);
    sizeField[0] = 0x80; // binary marker
    sizeField.writeUInt32BE(body.length, 8);
    const buf = tar(
      [makeHeader({ name: "brain-abc123/notes/big.md", sizeField }), body],
      entry({ name: "brain-abc123/notes/after.md" }, "still here"),
      END
    );
    const got = files(buf);
    expect(got.get("notes/big.md")).toBe(body.toString("utf8"));
    expect(got.get("notes/after.md")).toBe("still here");
  });

  it("OK: a size field padded with spaces instead of NUL still parses", () => {
    // Some writers use "         12 " rather than a NUL terminator. .trim() covers it.
    const buf = tar(
      entry({ name: "brain-abc123/notes/a.md", sizeField: "         12 " }, "0123456789"),
      entry({ name: "brain-abc123/notes/b.md" }, "next"),
      END
    );
    const got = files(buf);
    expect(got.get("notes/a.md")).toBe("0123456789");
    expect(got.get("notes/b.md")).toBe("next");
  });

  it("OK: directories are skipped, but a symlinked NOTE fails loud instead of vanishing", () => {
    // A symlinked note carries no payload, so it used to disappear from the corpus with no
    // signal — the brain would answer NOT IN BRAIN for a note that plainly exists. Silence is
    // the failure mode this reader has already had twice, so a link the operator can fix is an error.
    const dirs = tar(entry({ name: "brain-abc123/notes/", type: "5" }),
                     entry({ name: "brain-abc123/notes/real.md", type: "0" }, "real"), END);
    expect(untar(dirs)).toEqual([["notes/real.md", "real"]]);

    for (const type of ["2", "1"]) {
      const buf = tar(entry({ name: "brain-abc123/notes/link.md", type }), END);
      expect(() => untar(buf, isLive)).toThrow(/link, not a file/);
    }
  });
});

