/**
 * hard-corpus — adversarial edge cases for the hand-rolled tar reader and the corpus cache.
 *
 * Companion to tests/corpus.test.ts, which covers the happy path and the ustar `prefix`
 * regression. Nothing here duplicates that file.
 *
 * Every test here asserts the CORRECT behaviour and passes. Nine of them were written as
 * failing tests against the reader as it stood, and the comments on those still explain the
 * bug they caught — a pax header dropping a note, a negative size looping forever, two cold
 * requests building the corpus twice — so the reason each guard exists survives the fix.
 *
 * Every BUG test's comment says whether the input is REACHABLE (GitHub's own tarball can
 * contain it) or THEORETICAL (only a malformed/hostile archive produces it). That distinction
 * is the whole point: the tarball is generated by `git archive` on GitHub's side, so the
 * reachable set is exactly "what git emits", not "what the tar spec permits".
 */
import { describe, expect, it, beforeEach, afterEach } from "vitest";
import http from "node:http";
import type { AddressInfo } from "node:net";
import zlib from "node:zlib";
import { untar, isLive, loadCorpus, __setCache } from "../lib/corpus";

const BLOCK = 512;
const END = Buffer.alloc(BLOCK * 2); // the two zero blocks that terminate an archive

/** One 512-byte ustar header. `sizeField` overrides the encoded size for the liar tests. */
function makeHeader(o: {
  name?: string;
  prefix?: string;
  size?: number;
  sizeField?: Buffer | string;
  type?: string;
}): Buffer {
  const h = Buffer.alloc(BLOCK);
  h.write(o.name ?? "", 0, 100, "utf8");
  h.write("0000644\0", 100, 8, "ascii");
  const raw = o.sizeField ?? (o.size ?? 0).toString(8).padStart(11, "0") + "\0";
  if (Buffer.isBuffer(raw)) raw.copy(h, 124, 0, Math.min(raw.length, 12));
  else h.write(raw, 124, 12, "ascii");
  h.write(o.type ?? "0", 156, 1, "ascii");
  h.write("ustar\0" + "00", 257, 8, "ascii");
  h.write(o.prefix ?? "", 345, 155, "utf8");
  return seal(h);
}

/**
 * Write the ustar header checksum. Every real tar writer does this, and untar now rejects
 * headers that fail it — that check is what stops a mis-measured entry's payload being parsed
 * as headers. A fixture without a checksum is not a tar, so sealing here keeps these tests
 * testing the format rather than a shape no writer emits.
 */
export function seal(h: Buffer): Buffer {
  h.write(" ".repeat(8), 148, 8, "ascii");
  let sum = 0;
  for (let i = 0; i < BLOCK; i++) sum += h[i];
  h.write(sum.toString(8).padStart(6, "0") + "\0 ", 148, 8, "ascii");
  return h;
}

/** Header + payload padded to a block boundary, the way a real writer emits it. */
function entry(o: Parameters<typeof makeHeader>[0], body: string | Buffer = ""): Buffer[] {
  const data = Buffer.isBuffer(body) ? body : Buffer.from(body, "utf8");
  const pad = Buffer.alloc(Math.ceil(data.length / BLOCK) * BLOCK - data.length);
  return [makeHeader({ size: data.length, ...o }), data, pad];
}

const tar = (...parts: Array<Buffer | Buffer[]>) => Buffer.concat(parts.flat());
const files = (buf: Buffer) => new Map(untar(buf));

/** git's strbuf_append_ext_header: "<len> <key>=<value>\n", where len counts its own digits. */
function paxRecord(key: string, value: string): string {
  const rest = key.length + value.length + 3; // " ", "=", "\n"
  for (let digits = 1; digits <= 6; digits++) {
    if (String(rest + digits).length === digits) return `${rest + digits} ${key}=${value}\n`;
  }
  throw new Error("unreachable");
}

/**
 * A Buffer whose reads are budgeted, so a non-terminating parse throws instead of hanging
 * the test process. untar only ever calls toString(), indexes bytes and reads .length.
 */
function budgeted(buf: Buffer, budget: number): Buffer {
  let n = 0;
  return new Proxy(buf, {
    get(t, prop) {
      if (prop === "toString") {
        return (...args: unknown[]) => {
          if (++n > budget) throw new Error("ITERATION_BUDGET");
          return (t.toString as (...a: unknown[]) => string)(...args);
        };
      }
      const v = Reflect.get(t, prop, t);
      return typeof v === "function" ? (v as Function).bind(t) : v;
    },
  }) as Buffer;
}

